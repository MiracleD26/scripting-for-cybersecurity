number = int(input("Enter a number between 20 and 50: "))

print("Bitwise AND with 30:", number & 30)
print("Bitwise OR with 30:", number | 30)
print("Bitwise XOR with 30:", number ^ 30)
print("Bitwise NOT:", ~number)
print("Bitwise right shift by 5 positions:", number >> 5)
print("Bitwise left shift by 3 positions:", number << 3)